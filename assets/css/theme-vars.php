if (!function_exists('medic_theme_var_table_exists')) {
    function medic_theme_var_table_exists(string $table): bool
    {
        global $pdo;

        try {
            if (!isset($pdo)) {
                return false;
            }

            $stmt = $pdo->prepare("
                SELECT COUNT(*)
                FROM INFORMATION_SCHEMA.TABLES
                WHERE TABLE_SCHEMA = DATABASE()
                AND TABLE_NAME = :table
            ");
            $stmt->execute([':table' => $table]);

            return (int)$stmt->fetchColumn() > 0;
        } catch (Throwable $e) {
            return false;
        }
    }
}

if (!function_exists('medic_theme_var_setting')) {
    function medic_theme_var_setting(string $key, string $default = ''): string
    {
        global $pdo;

        static $settings_cache = null;

        if ($settings_cache === null) {
            $settings_cache = [];

            try {
                if (isset($pdo) && medic_theme_var_table_exists('site_settings')) {
                    $stmt = $pdo->query("SELECT setting_key, setting_value FROM site_settings");

                    foreach ($stmt->fetchAll(PDO::FETCH_ASSOC) as $row) {
                        $settings_cache[(string)$row['setting_key']] = (string)$row['setting_value'];
                    }
                }
            } catch (Throwable $e) {
                $settings_cache = [];
            }
        }

        $value = trim((string)($settings_cache[$key] ?? ''));

        return $value !== '' ? $value : $default;
    }
}

if (!function_exists('medic_theme_var_color')) {
    function medic_theme_var_color(string $key, string $default): string
    {
        $value = medic_theme_var_setting($key, $default);

        return preg_match('/^#[0-9a-fA-F]{6}$/', $value) ? $value : $default;
    }
}

