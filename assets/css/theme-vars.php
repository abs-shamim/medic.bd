if (is_file($theme_vars_cache_file) && (time() - filemtime($theme_vars_cache_file)) < THEME_VARS_CACHE_TTL) {
    header('Content-Type: text/css; charset=utf-8');
    header('Cache-Control: public, max-age=' . THEME_VARS_CACHE_TTL);
    readfile($theme_vars_cache_file);
    exit;
}

