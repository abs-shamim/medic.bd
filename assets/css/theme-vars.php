/*
|--------------------------------------------------------------------------
| Response Cache
|--------------------------------------------------------------------------
| This file is requested as a <link rel="stylesheet"> on every single page
| view, so without a cache it ran a full site_settings query and a PHP
| bootstrap on every visitor's every page load. It now serves a plain
| static file for THEME_VARS_CACHE_TTL seconds (regenerated by whichever
| visitor's request finds it stale) and tells the browser to cache it for
| the same window, instead of hitting the database each time.
|--------------------------------------------------------------------------
*/
